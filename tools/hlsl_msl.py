#!/usr/bin/env python3
"""HLSL -> Metal Shading Language for the Metal RHI backend (src/render/CMakeLists.txt runs it at build time) and the
launcher's Metal renderer (launcher/CMakeLists.txt). Standard library only.

    python tools/hlsl_msl.py --glslang PATH --spirv-cross PATH --stage vert|frag --entry vs_main
                             --name kGsDrawVS_msl --out gs_draw_vs.msl.h [-D NAME=VALUE ...] SOURCE.hlsl

The one HLSL source (docs/NATIVE_RENDERER.md) goes through glslang to SPIR-V - as tools/hlsl_spirv.py, with its
dual-source patch (the second colour output at Location 0 Index 1, MSL's [[color(0), index(1)]]) - and SPIRV-Cross to
MSL. Metal has a table per kind (buffers, textures, samplers) and only 16 sampler slots, so the D3D11 registers map
straight to the slots: cbuffer bN -> [[buffer(N)]], texture tN -> [[texture(N)]], sampler sN -> [[sampler(N)]]
(--msl-decoration-binding; no binding shifts as for Vulkan). Vertex buffers are bound at buffer 30 by the backend.

Clip space needs no flip: Metal's is D3D's (y up, depth 0..1). VCS_SPIRV=1 is defined as for Vulkan (the point size,
which Metal needs for points too); VCS_MSL=1 as well, and VCS_MSL_VERTEX=1 for vertex shaders.

The entry point is `vcs_main` in every module: the device compiles one library per shader at run time
(newLibraryWithSource - the Command Line Tools have no Metal compiler; the OS has one). The header holds the MSL text as
`static const char <name>[]`.
"""
import argparse
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hlsl_spirv  # noqa: E402

ENTRY = "vcs_main"
MSL_VERSION = "30000"  # Metal 3 (macOS 13, every Apple Silicon Mac)


def compile_msl(glslang, spirv_cross, stage, entry, defines, source, workdir):
    """The MSL text of one entry point of `source`."""
    fd, spv = tempfile.mkstemp(suffix=".spv", dir=workdir)
    os.close(fd)
    fd, patched = tempfile.mkstemp(suffix=".spv", dir=workdir)
    os.close(fd)
    try:
        cmd = [glslang, "-D", "-V", "--target-env", "vulkan1.3", "-DVCS_SPIRV=1", "-DVCS_MSL=1"]
        if stage == "vert":
            cmd.append("-DVCS_MSL_VERTEX=1")  # the point size: an output of the vertex stage only
        cmd += ["-D" + d for d in defines]
        cmd += ["-S", stage, "-e", "main", "--source-entrypoint", entry, "-o", spv, source]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout + result.stderr)
            sys.exit("hlsl_msl: glslang failed on %s %s" % (source, entry))
        with open(spv, "rb") as f:
            words = hlsl_spirv.patch_dual_source(hlsl_spirv.words_of(f.read()))
        import struct
        with open(patched, "wb") as f:
            f.write(struct.pack("<%dI" % len(words), *words))
        cmd = [spirv_cross, patched, "--msl", "--msl-version", MSL_VERSION, "--msl-decoration-binding",
               "--rename-entry-point", "main", ENTRY, stage]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout + result.stderr)
            sys.exit("hlsl_msl: SPIRV-Cross failed on %s %s" % (source, entry))
        return result.stdout
    finally:
        for p in (spv, patched):
            try:
                os.remove(p)
            except OSError:
                pass


def write_header(path, name, msl, source, entry, defines):
    delimiter = "vcs_msl"
    if (")" + delimiter + '"') in msl:
        sys.exit("hlsl_msl: the MSL holds the raw string's delimiter")
    lines = ["// Generated by tools/hlsl_msl.py from %s (%s%s) - do not edit." % (
                 os.path.basename(source), entry, "".join(" " + d for d in defines)),
             "#pragma once",
             'static const char %s[] = R"%s(%s)%s";' % (name, delimiter, msl, delimiter)]
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--glslang", required=True)
    ap.add_argument("--spirv-cross", required=True)
    ap.add_argument("--stage", required=True, choices=("vert", "frag"))
    ap.add_argument("--entry", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--msl-out", help="also write the MSL text itself here (to read or check it)")
    ap.add_argument("-D", dest="defines", action="append", default=[])
    ap.add_argument("source")
    a = ap.parse_args()
    workdir = os.path.dirname(os.path.abspath(a.out))
    os.makedirs(workdir, exist_ok=True)
    msl = compile_msl(a.glslang, a.spirv_cross, a.stage, a.entry, a.defines, a.source, workdir)
    if a.msl_out:
        with open(a.msl_out, "w", encoding="utf-8", newline="\n") as f:
            f.write(msl)
    write_header(a.out, a.name, msl, a.source, a.entry, a.defines)


if __name__ == "__main__":
    main()
